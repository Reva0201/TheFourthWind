/* Turns the captured listing into src/venues.js.
   Per-room prices for the "listed but not bookable" clubs were read from their
   venue pages; the three bookable clubs additionally carry booking config. */

import fs from "node:fs";

const raw = JSON.parse(fs.readFileSync("venue-raw.json", "utf8"));

/* Extra detail for the five listed clubs, transcribed from their pages. */
const LISTED = {
  "angin-timur-mahjong-club": {
    open_label: "12:00 – 24:00",
    min_booking_hours: 2,
    description:
      "Club mahjong komunitas di Taman Palem — 8 meja ber-AC, parkir ruko luas, ramai Jumat sampai Minggu malam.",
    room_detail: [
      { name: "Meja Manual", tables: 4, base: 55000 },
      { name: "Meja Otomatis", tables: 4, base: 75000 },
    ],
  },
  "mah-bar-mahjong-bareng": {
    open_label: "10:00 – 24:00",
    min_booking_hours: 1,
    description: "",
    room_detail: [
      { name: "Meja Reguler", tables: 8, base: 75000 },
      { name: "Ruang VIP", tables: 4, base: 95000 },
    ],
  },
  mahjongqu: {
    open_label: "10:00 – 24:00",
    min_booking_hours: 4,
    description:
      "Venue demo resmi. Di sini calon venue dan tim kami mencoba alur booking, kasir, dan laporan — bukan tempat main sungguhan, dan tidak ada transaksi nyata.",
    room_detail: [
      { name: "Meja Manual", tables: 6, base: 60000 },
      { name: "Meja Otomatis", tables: 6, base: 80000 },
    ],
  },
  "angin-timur-mahjong-club-puri": {
    description: "",
    open_label: "",
    min_booking_hours: 2,
    room_detail: [
      { name: "Meja Manual", tables: 10, base: 85000 },
      { name: "Meja Otomatis", tables: 8, base: 120000 },
    ],
  },
  "young-mahjong": {
    description: "",
    open_label: "",
    min_booking_hours: 1,
    // Shown as a range on the page: "Rp 45.000 – Rp 55.000/jam".
    room_detail: [{ name: "Meja Otomatis", tables: 6, base: 45000, baseMax: 55000 }],
  },
};

const venues = raw.map((v) => {
  const extra = LISTED[v.s];

  const out = {
    name: v.n,
    slug: v.s,
    address: v.a,
    city: "",
    listed: !!v.listed,
    bookable: !!v.bookable,
    price_from: v.p ?? 0,
    table_count: v.t ?? 0,
    room_types: v.r ?? [],
    banner: v.banner ?? null,
    whatsapp: v.wa ?? null,
    showMabar: !!v.mabar,
  };

  // City is the trailing segment of the address as the listing renders it.
  const parts = v.a.split(", ");
  out.city = parts.length > 1 ? parts[parts.length - 1] : "";

  if (extra) {
    out.description = extra.description;
    out.open_label = extra.open_label;
    out.min_booking_hours = extra.min_booking_hours;
    out.tax_rate_bp = 1000;
    out.rooms = extra.room_detail;
  }

  return out;
});

const out = `/* ============================================================
   The Fourth Wind — venue directory
   ${venues.length} clubs · ${venues.filter((v) => v.listed).length} listed · ${venues.filter((v) => v.bookable).length} bookable online.
   Generated by build-venues.mjs — edit that script, not this file.
   ============================================================ */

export const VENUES = ${JSON.stringify(venues, null, 2)};
`;

fs.writeFileSync("src/venues.js", out, "utf8");
console.log(
  `src/venues.js — ${venues.length} total · ${venues.filter((v) => v.listed).length} listed · ${venues.filter((v) => v.bookable).length} bookable`
);
